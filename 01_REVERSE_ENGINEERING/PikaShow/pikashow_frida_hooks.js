// Pikashow 10.8.2 (com.offshore.pikachu) — Frida hooks
// Purpose: capture the live content-API base URL + signed request headers at runtime.
// The base URL is set from native code (libpika.so -> NativeWrapper.setUrl),
// so hooking setUrl is the direct way to see the host.
//
// Run (PC, phone connected over USB, USB debugging on):
//   frida -U -f com.offshore.pikachu -l pikashow_frida_hooks.js --no-pause
//
// What to look for in the output:
//   [*] NativeWrapper.setUrl -> https://<API HOST>/   <-- the live API host
//   [*] getHeadersV2 ...                              <-- signed headers per request
//   [*] HTTP GET/POST <full url>                      <-- every API call
//
// Safety notes:
// - Install the ORIGINAL APK, do NOT repack/modify it: libpika.so checks the
//   DEX/manifest/signature and can kill the app (delayed suicide) if tampered.
// - If the app closes by itself shortly after launch, the anti-tamper may have
//   spotted Frida — stop, note the last lines of output, and report back.

Java.perform(function () {
    // 0. Confirm the native lib loaded
    try {
        var Sys = Java.use('java.lang.System');
        Sys.loadLibrary.implementation = function (name) {
            console.log('[*] loadLibrary: ' + name);
            return this.loadLibrary(name);
        };
    } catch (e) { console.log('[!] loadLibrary hook failed: ' + e); }

    // 1. THE target: Retrofit base URL (live API host), set from native code.
    try {
        var NW = Java.use('com.offshore.raichu.natives.NativeWrapper');
        NW.setUrl.implementation = function (url) {
            console.log('[*] NativeWrapper.setUrl -> ' + url);
            return this.setUrl(url);
        };
        console.log('[+] Hooked NativeWrapper.setUrl');
    } catch (e) { console.log('[!] NativeWrapper hook failed: ' + e); }

    // 2. Signed headers generated by libpika.so for every API call.
    try {
        var P = Java.use('com.offshore.raichu.natives.Pikachu');
        P.getHeadersV1.implementation = function (ts, map) {
            var r = this.getHeadersV1(ts, map);
            console.log('[*] getHeadersV1 ts=' + ts + ' headers=' + map.toString());
            return r;
        };
        P.getHeadersV2.implementation = function (ts, map, path, query) {
            var r = this.getHeadersV2(ts, map, path, query);
            console.log('[*] getHeadersV2 path=' + path + ' query=' + query + ' headers=' + map.toString());
            return r;
        };
        console.log('[+] Hooked Pikachu.getHeadersV1/V2');
    } catch (e) { console.log('[!] Pikachu hook failed: ' + e); }

    // 3. Every HTTP request URL (OkHttp) — full path incl. /v1/api/videos etc.
    try {
        var Client = Java.use('okhttp3.OkHttpClient');
        Client.newCall.implementation = function (request) {
            try {
                console.log('[*] HTTP ' + request.method() + ' ' + request.url().toString());
            } catch (e2) { console.log('[*] HTTP (url unreadable): ' + e2); }
            return this.newCall(request);
        };
        console.log('[+] Hooked OkHttpClient.newCall');
    } catch (e) { console.log('[!] OkHttp hook failed: ' + e); }

    console.log('[+] pikashow_frida_hooks.js loaded — open the app and browse content.');
});
